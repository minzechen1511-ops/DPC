export function mergeResourceDirectory(
  existing?: GateAResourceEntry[]
): GateAResourceEntry[] {
  const byId = new Map((existing || []).map((item) => [item.id, item]));
  return INITIAL_GATE_A_RESOURCES.map((seed) => {
    const saved = byId.get(seed.id);
    if (!saved) return { ...seed };
    return {
      ...seed,
      accessStatus: saved.accessStatus || seed.accessStatus,
      httpStatus: saved.httpStatus,
      lastCheckedAt: saved.lastCheckedAt,
      lastCheckNote: saved.lastCheckNote,
      resolvedURL: saved.resolvedURL || seed.resolvedURL,
    };
  });
}
